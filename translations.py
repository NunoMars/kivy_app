def get_system_language():
    """Détecte la langue du système.

    Comportement:
    - Si `set_app_language()` a forcé `_FORCED_LANG`, on l'utilise.
    - Si la variable d'environnement `APP_LANG` est définie, on l'utilise.
    - Tente la détection Android via `pyjnius` si disponible.
    - Tombe ensuite sur la locale système Python.
    - Normalise les codes (pt_br, pt-br -> pt, es_latam -> es_latam ou es)
    - Si la langue détectée n'est pas dans `MESSAGES`, on tente une correspondance
      par préfixe (ex: 'pt_BR' -> 'pt', 'es_MX' -> 'es').

    Retourne une clé présente dans `MESSAGES` (ex: 'fr','en','pt','pt_br','es_latam','ru','ja','tr','zh', ...)
    ou 'fr' par défaut.
    """
    # 1) forced lang set by set_app_language
    try:
        if _FORCED_LANG:
            return _FORCED_LANG
    except NameError:
        pass

    # 2) env override
    try:
        env = os.environ.get('APP_LANG')
        if env:
            candidate = str(env).strip().lower()
            return _best_lang_match(candidate)
    except Exception:
        pass

    # 3) Android / pyjnius
    try:
        from jnius import autoclass
        Locale = autoclass('java.util.Locale')
        lang = str(Locale.getDefault().getLanguage())
        country = str(Locale.getDefault().getCountry())
        candidate = (lang + ("_" + country if country else "")).lower()
        return _best_lang_match(candidate)
    except Exception:
        pass

    # 4) desktop locale
    try:
        import locale as _locale
        system_locale = _locale.getdefaultlocale()[0]
        if system_locale:
            return _best_lang_match(system_locale)
    except Exception:
        pass

    # default
    return 'fr'


def _best_lang_match(candidate: str) -> str:
    """Retourne la meilleure clé de langue correspondant à `candidate`.

    Cherche dans `MESSAGES` : exact, variantes normalisées (pt_br->pt_br puis pt),
    préfixes (pt_BR -> pt), puis fallback 'en' ou 'fr'.
    """
    if not candidate:
        return 'fr'

    c = candidate.lower().replace('-', '_')

    # direct key match
    if c in MESSAGES:
        return c

    # map common aliases
    alias_map = {
        'pt_br': 'pt_br',
        'pt_br_br': 'pt_br',
        'pt': 'pt',
        'es_latam': 'es_latam',
        'es_mx': 'es',
        'en_us': 'en',
        'en_gb': 'en',
        'zh_cn': 'zh',
        'zh_tw': 'zh',
        'ja': 'ja',
        'ru': 'ru',
        'tr': 'tr',
    }
    for k, v in alias_map.items():
        if c.startswith(k):
            if v in MESSAGES:
                return v

    # try prefix (language only)
    lang_part = c.split('_', 1)[0]
    if lang_part in MESSAGES:
        return lang_part

    # fallback to english if available, otherwise french
    if 'en' in MESSAGES:
        return 'en'
    return 'fr'

def tr(key, **kwargs):
    """Traduit une clé selon la langue du système"""
    current_language = get_system_language()
    
    messages_dict = dict(MESSAGES)
    if current_language in messages_dict and key in messages_dict[current_language]:
        message = messages_dict[current_language][key]
    elif 'fr' in messages_dict and key in messages_dict['fr']:
        message = messages_dict['fr'][key]
    else:
        message = key  # Retourne la clé si aucune traduction
    
    # Formatter avec les paramètres si nécessaire
    try:
        return message.format(**kwargs)
    except:
        return message


def set_app_language(lang: str):
    """Force la langue utilisée par les fonctions de traduction.

    Appelée par `main.py` après la détection principale pour garantir
    que tous les modules utilisent la même langue durant l'exécution.
    """
    global _FORCED_LANG
    try:
        _FORCED_LANG = lang
    except Exception:
        _FORCED_LANG = None
