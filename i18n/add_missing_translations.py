# Mettre à jour chaque fichier
for lang_code, new_keys in translations.items():
    filename = f"{lang_code}.json"
    try:
        with open(filename, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Ajouter les nouvelles clés
        added = 0
        for key, value in new_keys.items():
            if key not in data['messages']:
                data['messages'][key] = value
                added += 1
        
        # Sauvegarder
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        
        print(f"✅ {filename:15s} : {added} clé(s) ajoutée(s)")
    except Exception as e:
        print(f"❌ {filename:15s} : ERREUR - {e}")

print("\n✅ Toutes les traductions ont été ajoutées!")
